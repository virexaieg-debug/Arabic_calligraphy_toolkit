    def display_all_inks(self):
        result = "墨 **دليل الأحبار التجاري المعتمد للخط العربي:**\n"
        for _, row in self.df.iterrows():
            result += (
                f"\n📌 **{row['الحبر']}**\n"
                f"   - النوع: {row['النوع']} | الألوان: {row['الألوان']}\n"
                f"   - الحجم: {row['الحجم']} | بلد الصنع: {row['بلد الصنع']}\n"
                f"   - الاستخدام المثالي: {row['الاستخدام المثالي']}\n"
            )
        return result

    def search_ink(self, keyword):
        mask = (
            self.df['الحبر'].astype(str).str.contains(keyword, na=False) |
            self.df['النوع'].astype(str).str.contains(keyword, na=False) |
            self.df['الاستخدام المثالي'].astype(str).str.contains(keyword, na=False) |
            self.df['بلد الصنع'].astype(str).str.contains(keyword, na=False)
        )
        filtered_df = self.df[mask]
        
        if filtered_df.empty:
            return f"❌ لم يتم العثور على نتائج تطابق البحث عن: ({keyword})"
        
        result = f"🔍 **نتائج البحث عن ({keyword}):**\n"
        for _, row in filtered_df.iterrows():
            result += (
                f"\n📌 **{row['الحبر']}** ({row['النوع']})\n"
                f"   - الألوان المتاحة: {row['الألوان']}\n"
                f"   - الحجم: {row['الحجم']} | الصنع: {row['بلد الصنع']}\n"
                f"   - الاستخدام المثالي: {row['الاستخدام المثالي']}\n"
            )
        return result
