    def display_all_papers(self):
        result = "📜 **دليل أنواع الورق واستخداماتها في الخط العربي:**\n"
        for _, row in self.df.iterrows():
            result += (
                f"\n📌 **{row['الورقة']}** ({row['النوع']})\n"
                f"   - الخامة: {row['الخامة']}\n"
                f"   - المقاسات: {row['المقاس']}\n"
                f"   - الخطوط المناسبة: {row['نوع الخط المناسب']}\n"
            )
        return result

    def search_paper(self, keyword):
        mask = (
            self.df['الورقة'].astype(str).str.contains(keyword, na=False) |
            self.df['النوع'].astype(str).str.contains(keyword, na=False) |
            self.df['نوع الخط المناسب'].astype(str).str.contains(keyword, na=False) |
            self.df['الخامة'].astype(str).str.contains(keyword, na=False)
        )
        filtered_df = self.df[mask]
        
        if filtered_df.empty:
            return f"❌ لم يتم العثور على نتائج تطابق البحث عن: ({keyword})"
        
        result = f"🔍 **نتائج البحث عن الورق ({keyword}):**\n"
        for _, row in filtered_df.iterrows():
            result += (
                f"\n📌 **{row['الورقة']}** ({row['النوع']})\n"
                f"   - الخامة: {row['الخامة']}\n"
                f"   - المقاسات: {row['المقاس']}\n"
                f"   - الخطوط المناسبة: {row['نوع الخط المناسب']}\n"
            )
        return result
